import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PW_PATH || 'playwright');
const SHOT = process.env.SHOT || '/tmp/claude-0/-home-user-invexia3/62fbc2c4-2ed1-5ca7-94a2-3ae29a304854/scratchpad';
const browser = await chromium.launch({ args: ['--enable-unsafe-swiftshader', '--ignore-gpu-blocklist', '--enable-webgl'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
const errs = [];
page.on('console', (m) => { if (m.type() === 'error' || m.type() === 'warning') errs.push(`${m.type()}: ${m.text()}`); });
page.on('pageerror', (e) => errs.push('pageerror: ' + e.message));
await page.addInitScript(() => { window.__VELOCITY_TEST = { quality: 'low', noLock: true }; });
const t0 = Date.now();
await page.goto('file:///home/user/invexia3/web/dist/velocity-fps.html');
await page.waitForFunction(() => !document.getElementById('play').disabled, null, { timeout: 120000 });
console.log('chargement', Date.now() - t0, 'ms');
await page.waitForTimeout(1500);
await page.screenshot({ path: `${SHOT}/01-title.png` });
await page.click('#play');
await page.waitForTimeout(2500);
await page.screenshot({ path: `${SHOT}/02-spawn.png` });
console.log(JSON.stringify(await page.evaluate(() => window.__velocity.state()), null, 0).slice(0, 900));
console.log(errs.slice(0, 20).join('\n'));
await browser.close();
